let current = null;

/** The ot's language (project identity, else the global one): its texts follow it. */
function identityLang() {
  for (const f of [projectFile('identity.json'), homeFile('identity.json')]) {
    const l = readJson(f)?.language;
    if (l) return String(l).slice(0, 2).toLowerCase();
  }
  return '';
}

export function cliLang() {
  if (current) return current;
  const pick = (v) => (['en', 'es', 'pt'].includes(v) ? v : '');
  current =
    pick(process.env.SEVENOTS_LANG) ||
    pick(readJson(homeFile('config.json'), {})?.lang) ||
    pick(identityLang()) ||
    pick(String(process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG || '').slice(0, 2).toLowerCase()) ||
    'en';
  return current;
}

export function setCliLang(l) {
  if (M[l]) current = l;
}

/** t(key, vars) or t(key, lang, vars). */
export function t(key, a, b) {
  const lang = typeof a === 'string' ? a : cliLang();
  const vars = (typeof a === 'string' ? b : a) || {};
  const s = (M[lang] || M.en)[key] ?? M.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
